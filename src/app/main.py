from fastapi import FastAPI, Query, Body # import FastAPI class from Starlette
from pydantic import BaseModel, EmailStr, Field
from typing import Annotated, Literal
from enum import Enum


from src.app.modules.tasks.router import router as tasks

from fastapi.security import (
    OAuth2PasswordBearer, 
    OAuth2PasswordRequestForm, 
    SecurityScopes
)


oauth2_schema = OAuth2PasswordBearer(
    tokenUrl="token",
    scopes={
        "user:normal":"Only modified and see own task",
        "user:admin" : "See users list task and Modify system"
    }
)



app = FastAPI() # instance of class FastAPI




class Status(str, Enum):
    to_do = "To-do"
    in_progress = "In-progress"
    done = "Done"


class AddTask(BaseModel):
    task_no : str
    title : str
    status : Status
    description : str | None = None


class UpdateTask(BaseModel):
    title : str
    status : Literal["To-do", "In-progress", "Done"] = "To-do"
    description : str | None = None

class UpdateTaskResponse(BaseModel):
    task_no : str
    title : str
    status : Status
    description : str | None = None

class Register(BaseModel):
    email : EmailStr
    username : str
    password : str 


class Pagination(BaseModel):
    limit : int = Field(100, gt=0, le=100)
    offset : int = Field(0, ge=0)

@app.get("/", include_in_schema=False)
async def root():
    return {"msg":"FastAPI is Running!"}

@app.post("/status/{staus}", include_in_schema=False)
async def user(status : Status, description : str) -> dict:
        
    return {"Status":status, "desc":description}

@app.get("/files/{file_path:path}", include_in_schema=False)
async def user(file_path : str) -> dict:
        
    return {"File_Upload":file_path}


""" Add User """
@app.post("/register")
def register(user : Register) -> dict:
    return {**user.model_dump()}


""" Task router """
app.include_router(
    tasks,
    tags=["Tasks"],
    prefix="/api/v1"
)

""" Update status """
@app.patch("/tasks/{task_no}", response_model=UpdateTaskResponse)
def update_task(task_no : str, status : Status) -> dict:

    for task in tasks_list:
        if task["task_no"] == task_no:
            task["status"] = status
            return task

""" Update task information """
@app.put("/tasks/{task_no}", response_model=UpdateTaskResponse)
def update_info(task_no : str, task_update : UpdateTask):
    for task in tasks_list:
        if task["task_no"] == task_no:
            return {
                "task_no": task["task_no"],
                **task_update.model_dump()
            }

""" Delete task """
@app.delete("/task")
def delete_task(task_no : str):
    for task in tasks_list:
        if task["task_no"] == task_no:
            del task
            return {"msg" : "Task successfully deleted!"}
            

""" Filtered by status using query parameters """
@app.get("/tasks")
def filtered_by_status(status : Status | None = None, limit: int = 5) -> list[dict]:
    if not status:
        raise "Status Not Found"

    filtered_status =[
        task
        for task in tasks_list
        if task["status"] == status
    ]
    return filtered_status[:limit]

""" Search by ID and Title useing query parameter """
@app.get("/tasks/search")
def search_task(search : Annotated[str | None, Query(max_length=50)] = None )-> dict:

    for task in tasks_list:
        if search in task["task_no"] or search in task["title"]:
            return task
    return {"msg": "Task not found"}


""" Pagination """
@app.get("/tasks/list")
def task_list(
    page : Annotated[int, Query(ge=0)] = 0, 
    limit : Annotated[int, Query(gt=0, le=100)] = 10, 
):
    
    offset = (page - 1) * limit
    return tasks_list[offset:offset + limit]

